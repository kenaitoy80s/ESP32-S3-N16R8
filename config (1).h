// ===================== 播放 / 重连 =====================
// ---- 音量量程(2026-09-22 由 0..21 改为 0..99) ----
// 对外(网页滑块 / 按键与红外步进 / 屏幕百分比 / NVS 记忆 / /api 上报)统一用 0..99。
// ★底层库 ESP32-audioI2S-nopsram 【只有 22 档】, 是一张"每档约 1dB"的对数增益表:
//     const uint8_t volumetable[22]={0,1,2,3,4,6,8,10,12,14,17,20,23,27,30,34,38,43,48,52,58,64};
//     void Audio::setVolume(uint8_t vol){ if(vol > 21) vol = 21; m_vol = volumetable[vol]; }
//   表值即 6bit 增益(m_vol), Gain() 用 `(s * m_vol) >> 6` 衰减, 64 = 满增益 0dB。
//   ⚠★绝不可把 0..99 直接交给库: 库里 `vol>21 -> 21` 会把中间音量(例如 50)钳成【满音量】爆响。
//   故一律经 volToLib() 显式映射。副作用: 99 档里相邻 4~5 档落在同一个库档位上(听感一致),
//   这是底层 22 档分辨率的物理上限(每档 0.36dB, 低于人耳可辨阈值), 不是故障。
#define VOLUME_DEFAULT   57     // 默认音量(0..99); 57 ≈ 旧 21 档制的 12
#define VOLUME_MAX       99     // 对外音量上限(0 = 静音)
#define VOLUME_LIB_MAX   21     // 库内部档位上限(对应上表 22 项; 不要改)

// 对外音量(0..99) -> 库内部档位(0..21), 四舍五入到最近一档。
static inline uint8_t volToLib(int v) {
  if (v <= 0) return 0;
  if (v > VOLUME_MAX) v = VOLUME_MAX;
  return (uint8_t)((v * VOLUME_LIB_MAX + VOLUME_MAX / 2) / VOLUME_MAX);
}

