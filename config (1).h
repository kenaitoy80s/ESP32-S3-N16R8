// ============================================================================
// 双通道日志输出 (2026-09-18 S3 版新增) —— 同时写 UART0 与原生 USB 口, 且永不阻塞。
//   [问题一: 看不到日志] esp32s3 默认 Serial=Serial0(UART0, GPIO43/44); 板子另一侧的原生
//     USB 口(GPIO19/20, USB-Serial-JTAG)收不到应用日志 -> 插原生口就等于"串口没输出"。
//     本头把输出镜像给两个口, 输入命令(T/M/D/S/L/R/W/I/Z)也从两口读, 不用猜插哪个。
//   [问题二: 日志把主循环拖死 -> "屏显播放中却没声音"] HWCDC.write() 在"主机连了但不读"时
//     会塞满 TX 环形缓冲, 之后每次 write 要等 tx_timeout(core 的 HWCDC.cpp, 实测数百 ms)。
//     本工程每秒都在打心跳日志 -> 主循环被反复拖住 -> 音频缓冲喂空 -> 屏幕停"播放中"却无声;
//     setup 阶段则永远停在"开机中..."; store.loop() 不转 -> 电台改动不落盘。
//     对策: 初始化后 setTxTimeoutMs(0) => 写不进就丢, 绝不等待。
// ============================================================================
// 芯片是否带 USB-Serial-JTAG(S3/C3/S2 等)且内核处于 hwcdc 模式
#if defined(SOC_USB_SERIAL_JTAG_SUPPORTED) && SOC_USB_SERIAL_JTAG_SUPPORTED && defined(ARDUINO_USB_MODE) && ARDUINO_USB_MODE
#include "HWCDC.h"
#define WR_HAS_USB_CDC 1
#else
#define WR_HAS_USB_CDC 0
#endif

#if WR_HAS_USB_CDC
  #if ARDUINO_USB_CDC_ON_BOOT
    // 选了 "USB CDC On Boot: Enabled" -> core 已提供全局实例并完成 USB 初始化
    inline HWCDC& wrUsb() { return HWCDCSerial; }
    #define WR_USB_NEEDS_BEGIN 0
  #else
    // 未开 CDC on boot(本工程默认): core 不提供全局实例, 由本工程自建(定义在 webradio-s3p.ino)
    extern HWCDC wrUsbCdc;
    inline HWCDC& wrUsb() { return wrUsbCdc; }
    #define WR_USB_NEEDS_BEGIN 1
  #endif
#endif

class TeeLog : public Print {
public:
  // 初始化两个通道。UART0 不必设写超时: 它无流控, 硬件一定把 TX 缓冲排空, 不会长期阻塞。
  void begin(unsigned long baud = 115200) {
    Serial0.begin(baud);                       // 通道①: UART0 -> GPIO43/44
#if WR_HAS_USB_CDC
  #if WR_USB_NEEDS_BEGIN
    wrUsb().begin(baud);                       // 通道②: 原生 USB(USB-Serial-JTAG), 自行初始化
  #endif
    wrUsb().setTxTimeoutMs(0);                 // ★永不阻塞: 写不进去就丢, 绝不拖住主循环
#endif
  }

  // ---- 输出: 同时送两个通道(Print::print/println/printf 最终都落到 write) ----
  size_t write(uint8_t c) override {
    Serial0.write(c);
#if WR_HAS_USB_CDC
    wrUsb().write(c);
#endif
    return 1;
  }
  size_t write(const uint8_t* buffer, size_t size) override {
    Serial0.write(buffer, size);
#if WR_HAS_USB_CDC
    wrUsb().write(buffer, size);
#endif
    return size;
  }
  void flush() override {
    Serial0.flush();
#if WR_HAS_USB_CDC
    wrUsb().flush();
#endif
  }

  // ---- 输入: 任一口有字符即可(串口诊断命令用) ----
  int available() {
    int n = Serial0.available();
#if WR_HAS_USB_CDC
    n += wrUsb().available();
#endif
    return n;
  }
  int read() {
    int c = Serial0.read();
#if WR_HAS_USB_CDC
    if (c < 0) c = wrUsb().read();
#endif
    return c;
  }
  int peek() {
    int c = Serial0.peek();
#if WR_HAS_USB_CDC
    if (c < 0) c = wrUsb().peek();
#endif
    return c;
  }
};

