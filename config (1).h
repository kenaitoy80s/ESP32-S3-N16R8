//   只等【一帧】(AAC/MP3 一帧约 1~2KB)就开始解码输出。而本板 HE-AAC 台解码后输出
//   384KB/s(96kHz), 起播时输入缓冲几乎是空的、TCP 又刚开始慢启动 -> 缓冲在低位来回震荡,
//   I2S DMA(只有 170ms) 被反复排空 -> 听感就是"卡卡卡"。等缓冲被灌到几十 KB、抖动被吸收,
//   才"突然变流畅" —— 前面那十几秒基本是白等的。
// 【对策】在库的解码出口 Audio::playAudioData() 上加一道【最小缓冲闸门】(见库内 Patch 10):
//   缓冲没攒够就【不解码、不喂 I2S】, 于是缓冲能以全速往上涨(没有消耗), **一起声就是流畅的**;
//   运行中若缓冲跌破低水位(网络抖动), 也是"暂时不出声"而不是"碎音", 涨回来自动继续 ——
//   等于给电台加上了库本身没有的"再缓冲(re-buffer)"能力。高/低双水位构成滞回, 不会在阈值上抖。
// 【代价】换台后多等 0.7~4 秒(取决于码率)才出声, 但换来"第一声就流畅"。
// ★库里的宏名是 AUDIO_MIN_BUFFER_BYTES, 由 build_opt.h 传给编译器(库内有默认值 0 = 保持原行为)。
//   改这里时必须同时改 build_opt.h, 两处要一致。
#define AUDIO_PREBUF_BYTES   (32 * 1024)   // 高水位: 128kbps≈2.0s / 200kbps≈1.3s / 64kbps≈4.0s
