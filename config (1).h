// ===================== 音频泵任务(方案B, 2026-09-19) =====================
// 【为什么需要它】ESP32-audioI2S 2.0.6 是【单线程】库: audio.loop() 一次调用内完成
//   "拉流 + 解码 + 写 I2S"。所以【两次调用的间隔】直接决定音频连续性 —— 间隔超过 I2S DMA
//   深度(32×512 帧 = 96kHz 下 170ms / 44.1kHz 下 372ms), DMA 就排空, 听感就是"断断续续"。
// 【旧结构的病】它和 UI(软件 SPI 整屏刷新 56~63ms)/Flash 落盘/网页请求挤在同一个 Arduino
//   loopTask 里【顺序】执行: 显示刷一屏, 音频就断一次。之前靠 display_ui 里的"整帧跳过"hack
//   把那 60ms 压掉才勉强稳住(跳过率 94%) —— 属于用补丁换稳定, 代码可维护性差。
// 【新结构】音频独占一个高优先级任务, 钉 core1 与 loopTask【同核但优先级更高】:
//   loopTask 正在做长耗时(整屏刷新/写盘/处理网页请求)时, 音频泵能【抢占】它并按时喂 I2S,
//   喂流间隔不再受 UI 影响 —— "整帧跳过"随之从"救命补丁"降级为"省 CPU 的优化"。
// 【并发安全】库不接受并发调用, 故:
//   · 音频泵只调 audio.loop();
//   · 主循环侧一切碰 audio 对象的操作(stopSong / connecttohost / beep)都持同一把递归锁
//     audioMutex(见 AudioPlayer::lockAudio), 两者严格互斥;
//   · gState(含 String)始终【只由主循环写】—— 库回调 audio_showstreamtitle 在音频泵里执行,
//     它不直接写 gState, 而是写一个无堆分配的暂存缓冲 + 代次号, 由主循环取走(见 audio_player.cpp)。
// 【★防呆设计 2026-09-19: 方案B 永不可能"一坏就全哑"】
//   音频泵只是"更稳的喂流方式", 而不是唯一喂流路径。固件里始终保留【主循环喂流】作为回退:
//     · pumpEnabled=true  且 泵任务已创建  -> 只由泵任务调 audio.loop();
//     · pumpEnabled=false 或  泵任务缺失   -> 由 AudioPlayer::loop()(主循环)直接调 audio.loop()。
//   两条路径【互斥执行】(同一时刻只会有一条在跑), 所以不会重复喂流; 泵一旦没起来, 声音自动照旧。
//   串口发 P 可在真机上随时切换两种模式做 A/B 对比。见 audio_player.cpp 的 AudioPlayer::loop()。
#define AUDIO_PUMP_ENABLED   1      // 1=启用音频泵(推荐) 0=从一开始就用主循环喂流(方案A 回退)
#define AUDIO_TASK_CORE      1      // 钉 core1(与 loopTask 同核, 靠优先级抢占); 不选 core0 以免与 WiFi/lwIP 抢
#define AUDIO_TASK_PRIO      3      // > loopTask(1) 与失速看门狗(2)。每圈 vTaskDelay(1) 让出 1ms, 其余时间优先喂流
                                    // (3 是本工程 S3 上历史验证过的取值; 远低于 WiFi/tcpip 的 18~23, 不会干扰网络)
#define AUDIO_TASK_STACK     8192   // 任务栈(字节)。任务栈只能在内部 DRAM。
                                    // ★回到 8192: 2026-09-19 一度改成 16384, 结果 16KB 连续内部块不一定拿得到,
                                    //   任务创建失败会【静默回退成主循环喂流】——音频解码与 LCD 整屏刷新挤在一条线程,
                                    //   表现就是"一直卡卡卡"(比改造前还差)。已由 startPumpTask() 加创建失败梯子兜底。
                                    //   判据: 开机串口那行 [Audio] 音频泵任务已启动 里的"栈xxxB"就是真实生效值。
                                    // ★2026-09-19 从 8192 提到 16384: 本板跑的是【SBR 已编入】的 HE-AAC,
                                    //   audio.loop() -> sendBytes -> Helix AAC(+SBR) 的调用链比 MP3/LC 深得多,
                                    //   8KB 有栈溢出风险(溢出=直接 panic 重启, 现象就是"莫名没声音/重启")。
                                    //   内部堆还剩 ~260KB, 多给 8KB 无压力。
#define AUDIO_WDT_STUCK_S    30     // 音频泵失速看门狗阈值(s): 特意比 loop 的 15s 长, 避免慢速建连/等锁误判

// ===================== 红外遥控学习 =====================
// 需外接 VS1838B(38kHz 红外接收头): VCC→3.3V, GND→GND, OUT→IR_RX_PIN。
// 用 ESP32 原生 RMT 硬件接收(独立外设时钟, 不抢音频 I2S / WiFi 定时器),
// 学"任意遥控器"原始波形(不挑协议 NEC/RC5/Sony/...), 码存 NVS, 收到匹配码触发动作。
// 对单线程 / no-PSRAM 板零额外负担(接收在 RMT 中断里完成, 主循环只做轻量比对)。
#define IR_ENABLED      1       // 0 = 完全关闭(函数变空实现, 不占代码/外设)
#define IR_RX_PIN       4       // S3: 接收头 OUT 接 GPIO4(输入, 内部上拉; 非 strapping, RTC GPIO 可唤醒深睡)
#define IR_MAX_EDGES    128     // 单帧最大边沿数(决定能学多长的码; 128 足够覆盖 NEC/RC5/Sony)
#define IR_LEARN_MS     15000   // 学习模式超时(ms): 进入后多久没收到码自动取消
// 同键重复触发冷却: 按【动作类型】分别给值, 因为不同动作的"按住"语义不同 ——
//   · 音量(IR_VOL_REPEAT_MS): 按住 = 连续步进, 冷却要短(≈遥控重复帧间隔 110ms)才能顺滑连续调;
//   · 上一台/下一台(IR_TRIGGER_COOLDOWN_MS): 按住 = 每格跳一台, 350ms 一格手感合适;
//   · 播放/暂停、关机(IR_TOGGLE_COOLDOWN_MS): 单击 = 一次, 长按不应反复开关, 故冷却拉到 1500ms
//     (NEC 类遥控按住会按 ~110ms 间隔重发, 1500ms 内只算一次按压)。
#define IR_TRIGGER_COOLDOWN_MS 350   // prev / next: 每 350ms 一格
#define IR_VOL_REPEAT_MS       100   // volup / voldown: 按住连续步进(略小于 NEC 重复帧间隔 ~110ms, 保证每帧都步进)
#define IR_TOGGLE_COOLDOWN_MS  1500  // toggle / sleep: 单击一次即止, 防按住反复切换

// ---- 红外"长按"判定窗口(2026-09-21 新增, 2026-09-22 修正为"多帧确认") ----
// 红外遥控【没有】按下/松开事件, 只能靠协议里的【重复帧】识别"人还按着":
//   NEC 类遥控按住时, 首帧是完整码(已学, ~66 边沿), 之后每 ~110ms 发一个【短重复帧】(约 4 边沿)。
// 做法: IR_TOGGLE(播放/停止) 命中完整码时【先挂起不派发】, 观察窗口内的重复帧个数 ——
//   · 累计收到 IR_TOGGLE_HOLD_REPEATS 个重复帧 -> 判为长按 -> 触发 hold 事件(进入/退出电台列表),
//     取消待定的单击;
//   · 窗口到期仍未凑够                        -> 判为单击 -> 派发"播放/停止"(列表里则是【确定】)。
//
// ★2026-09-22 修正原因(现场反馈"长按能进列表, 但列表里按播放键不能确定"):
//   原实现是"窗口 150ms 内出现任意 1 个重复帧就算长按"。但 NEC 重复帧间隔只有 ~110ms, 而人
//   "单击"按键通常持续 100~250ms —— 也就是说【正常的单击也几乎必然收到 1 个重复帧】, 于是单击
//   被误判成长按: 在电台列表里按播放键想"确定", 结果执行的是"进入/退出列表"(列表直接收起, 没换台)。
//   改为"必须连续 2 个重复帧"(即按住 >= ~220ms)后:
//     · 单击(按住 ~150ms, 至多 1 个重复帧)      -> 判单击  ✓
//     · 长按(按住 >= ~220ms, 2 个及以上重复帧)  -> 判长按  ✓
// ⚠ 代价: 红外"播放/停止"的响应延迟从 150ms 变成 300ms(要等窗口过完才能确定不是长按);
//   红外"长按进列表"的触发点从 ~110ms 变成 ~220ms。功能正确性优先于这点延迟。
// ⚠ 少数遥控协议根本不发重复帧 -> 那种遥控用不了"长按", 只能靠实体键进列表(其它键不受影响)。
#define IR_TOGGLE_HOLD_MS      300   // 单击/长按的观察窗口(必须 > 2×重复帧间隔)
#define IR_TOGGLE_HOLD_REPEATS 2     // 窗口内累计这么多个重复帧才判"长按"(1 个只当单击时的顺带帧)

// 深睡唤醒后"指定遥控键开机"确认窗口(ms)。红外唤醒后, 只有在此窗口内收到【已学的 power 码】才真正开机;
// 否则(超时 / 收到其它遥控键)立刻回深睡 —— 相当于"只有那个关机键能开机, 别的键/别的遥控器都不行"。
// 注意: 深睡唤醒 -> RMT 武装 之间有数百 ms 时延, 而一次遥控帧仅约 110ms, 可能已结束; 若第一次按没反应,
//   请在窗口内【再按一下】该遥控键(部分遥控器长按会持续发完整帧, 长按也可)。
#define IR_WAKE_CONFIRM_MS     2000

// "有遥控活动"的最小边沿数: 收到的红外帧边沿数达到它, 就认为"用户在按遥控"并按亮屏处理。
// ★为什么不是"码匹配成功才算活动"(2026-10-08 修): 屏黑着时用户按遥控上任何一个【没学过】的键
//   (或这次命中被动作冷却吞掉)都不会走动作回调 —— 于是屏不亮, 用户以为设备死了。
//   但用户按遥控的意图就是"我要用这个设备", 亮屏这件事本来就该与"这个键有没有学会"无关。
// 取值 = 4: 与学习模式判定"点到真实遥控码"的门槛一致(见 ir_learn.cpp 的 `n >= 4`),
//   低于它的是空闲噪声/单个毛刺。误亮的代价只是背光点亮(20s 无操作后自动灭), 可忽略。
#define IR_ACTIVITY_MIN_EDGES  4

// 熄屏待机(睡眠定时器到点)下, 电源键/遥控电源键 = "开机":
//   ★2026-10-08 修: 旧实现里 IR_POWER / 电源键长按【无条件】进深度休眠, 于是
//   "定时睡眠后想用遥控开机"会反过来把设备关进深睡(黑到底), 再从深睡唤醒还得在
//   IR_WAKE_CONFIRM_MS 窗口内再按一次 —— 表现就是"遥控开机有问题"。
//   现在由 gState.sleepStandby 区分: 待机态 = 开机(亮屏+恢复播放); 播放中 = 照旧关机。
#define STANDBY_POWER_OPENS   1   // 0 = 关闭本行为(恢复旧语义: 待机下电源键仍直接关机)

// ===================== 开关机(深度休眠) + 功放使能 =====================
// 关机(深度休眠) = 停播 + 关 WiFi/蓝牙 + 清屏 + 功放关 + ESP32 进 deep sleep。
//   唤醒 = ①按电源键(拉低); ②按【已学成 "power" 动作的那一个遥控键】。注意②: 硬件唤醒只看 IR 脚是否拉低
//   (任何遥控码都会拉低), 故唤醒后由 ir_confirm_power() 软件确认 —— 只认已学 power 码, 其它键立刻回深睡。
// 两种"关机"途径:
//   ① 独立电源键(单击, POWER_BTN_PIN) —— 外接瞬时按键(INPUT_PULLUP, 按下=低);
//   ② 红外遥控已学成 "power" 动作的按键(遥控器上任一键学成 power 即可)。
// AMP_EN_PIN 接功放(MAX98357)的 EN/SD 使能脚, 语义按 S3 规格:
//   播放且【真正出声】时拉高(开启出声); 待机 / 停止 / 连接中 拉低(静音/关断)。
//   本固件由主循环 updateAmp() 动态驱动(以"是否真有音频数据在流"为判据, 而非仅 playing)。
//   若功放是【低电平使能】, 把 AMP_EN_ACTIVE 改成 LOW 即可。
// 注意: 唤醒脚须是【RTC GPIO, 可作 deep sleep 唤醒源】。
//   S3 上仅 GPIO0~21 属 RTC 域; 用户外设已占用其中 1,2,4~18,21, 剩下 0(BOOT)、3、19/20(原生USB)。
//   权衡后电源键选 GPIO3: 它的 strapping 只影响"JTAG 信号源", 不改变启动模式/Flash 电压,
//   正常启动与烧录都不受影响。
//   ★2026-09-21 更正: 原注释写"曾踩坑的 GPIO12/MTDI 会改 Flash 电压" —— 那是【ESP32 经典版】
//     的结论(经典版 GPIO12 = MTDI, strapping 拉高会选 1.8V VDD_SDIO -> Flash 起不来)。
//     ESP32-S3 的 strapping 脚只有 0 / 3 / 45 / 46, GPIO12 不参与(且 S3 上 MTDI 是 GPIO41)。
//     故本工程按键沿用 4M 版的 GPIO12 在 S3 上完全安全。
//   ★另注: GPIO0(BOOT) 固件未使用, 但它是启动模式 strapping(复位采样, 内部弱上拉=1=正常启动,
//     拉低=进下载模式)。切勿把 IO0 与任何按键脚短接(尤其中键 IO12) —— 详见 IO分配表.txt。
//   若你的板子 GPIO3 另有他用, 可改 0(BOOT, 但按住时会误入下载模式) 或 19/20(原生 USB, 会占 USB)。
#define POWER_BTN_PIN   3     // 独立电源键: 单击关机(进深度休眠); 深睡中按下=唤醒(ext0 低电平)
#define AMP_EN_PIN      21    // 功放使能 PA_ENABLE(输出; 出声=高, 静音/关机=低)
#define AMP_EN_ACTIVE   HIGH  // 功放"开启"电平(真正出声时拉到此电平)

// ===================== 电池电压检测 (2026-09-28 新增) =====================
// 单节锂电(1S, ≤4.2V)经两个 100k 串联分压: 中点 = Vbat/2, 接 BATT_ADC_PIN(ADC 输入)。
//   ★ 中点最高 2.1V < ESP32 IO 绝对上限 3.3V, 安全。
//   ★★ 若是 2S(≤8.4V): 中点 4.2V > 3.3V 会烧 IO! 必须改分压比(如 100k + 200k → 中点=Vbat/3)
//       或在中点加 3.3V 稳压管钳位。本项目按 1S 设计, 不要直接上 2S 不改动。
// 分压源阻抗约 50kΩ, 中点建议并一个 100nF 陶瓷电容到 GND: 稳定 ADC 采样 + 抑制 WiFi 射频纹波。
// 深睡也常流: 100k+100k=200k → 4.2V 时约 21µA(对 18650 可忽略; 要极致低功耗可在分压上端加 PMOS, 深睡断开)。
// BATT_ADC_PIN 选 17: 它是"零代价"空闲脚(17/18 二选一), ADC2_CH6, S3 上 ADC2 与 WiFi 不冲突
//   (经典 ESP32 才有 ADC2 被 WiFi 占用的坑, S3 没有), 联网播电台时也能正常采样。
#define BATT_ADC_PIN      17    // 电池分压中点(ADC 输入; 不要开内部上拉/下拉, 否则污染分压)
#define BATT_VREF         3.30f // ADC 参考电压(V); 片间有误差, 用 BATT_CAL 做一点校准
#define BATT_DIVIDER      2.0f  // 分压比 = (R上+R下)/R下 = 2 (两 100k 等分, 中点=Vbat/2)
#define BATT_CAL          1.0f  // 一点校准系数: 实测真 Vbat 后, BATT_CAL = 真值 / (raw/4095*3.3*分压比)
#define BATT_SAMPLES      8     // 每次采样平均次数(降噪)
#define BATT_POLL_MS      5000  // 主循环刷新间隔(ms)
#define BATT_EMPTY_V      3.30f // 电量 0% 对应电压(低于此视为没电/将关机); 单节锂电放到 3.0~3.3V 已空
#define BATT_FULL_V       4.20f // 电量 100% 对应电压(单节锂电满电)

// ===================== 充电状态检测 (2026-09-28 新增) =====================
