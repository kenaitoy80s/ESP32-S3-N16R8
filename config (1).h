// ===================== 起播预缓冲(2026-09-19 修"换台后卡十几秒") =====================
// 【现象】换台后要"卡卡地"唱十来秒才变流畅。
// 【根因】(读库源码确认, 不是猜) 库的起播门控极浅 —— Audio_nopsram.cpp:3072
