// ---- 网络收音机侧 TDA1387-A 供电控制(2026-09-22 新增: 补上被漏掉的电源管理) ----
// 【为什么必须"真断电", 而不是"不播 = 停喂 I2S = 数字静音"】三条理由:
//   ① 停喂 I2S 后 DMA 并【不保证】输出全 0 —— 传统 I2S 驱动在欠载时会继续把 DMA 缓冲里的
//      旧数据按原节奏送出去(是否清零取决于 dma_desc_auto_clear)。"没数据"≠"0 电平",
//      所以"停喂即静音"这个假设本身不成立。
//   ② 两颗 TDA1387 都是【电流输出型】DAC, 在合流点(各自 I/V + 阻容耦合后相加)上, 通电那颗
//      即便送 0 码也仍有静态电流与自身底噪 -> 会对被选中的那一路造成轻微串扰/底噪抬升。
//   ③ 待机/深度休眠: 网络 DAC 若常通电, 深睡电流从 µA 级跳到十几 mA(单颗 TDA1387 静态约 10mA),
//      "关机"就不是真关机了 —— 这正是本次要补的那一项。
// 语义(仅网络收音机: 网络侧 TDA1387-A 单独控制供电):
//   播放/待机 -> 本脚通电(网络侧 DAC 工作)
//   深度休眠 -> 本脚断电(真关机, 静耗从十几 mA 降到 µA 级)
//   (原 6686 第二音源已移除, 不再有"两路互斥"概念 —— 仅剩网络这一路)
// ★硬件前提: MOSFET 栅极务必加 10k 下拉到 GND —— 深睡时 ESP32 引脚是高阻, 没有下拉则开关
//   状态不定, "关机断电"会失效。这是本路唯一必须的硬件前提。
// -1 = 该路未接(固件自动跳过, 退回"仅数字静音"的旧行为)。
