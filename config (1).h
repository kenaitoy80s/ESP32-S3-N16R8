// ===================== 屏幕(ST7567 / SSD1306 / ST7789 / ILI9341 四选一) =====================
// 对比度/旋转(0/90/180/270°)/屏幕类型 在 Web 后台"显示设置"里调节并持久化(NVS "disp")。
// 2026-09-18 S3 版: 恢复双屏支持 —— ST7567(软件 SPI) 与 SSD1306(软件 I2C) 二选一;
// 2026-09-21: 新增 ST7789(硬件 SPI 彩色 TFT, 320x240), 后台"屏幕类型"下拉即时切换三种屏。
// 2026-09-22: ST7567 也从软件 SPI 改为【硬件 SPI】(撕裂消失, 见下方 LCD_BUS_SPI_HZ_*)。
//   SSD1306 自发光无背光脚; ST7567 / ST7789 / ILI9341 各有背光脚(LCD_BL / LCD2_BL)。
// ★★2026-10-09: 新增 ILI9341 适配 —— 与 ST7789【共用同一组引脚(LCD2_*)】, 后台"屏幕类型"下拉
//   里现场二选一, 【不用改线、不用重烧】: 换屏 = 换一块模块 + 后台选一下型号。
//   两者命令集(RESET/SLPOUT/DISPON/DISPOFF/INVON/COLMOD/MADCTL/CASET/PASET/RAMWR)与玻璃尺寸
//   (240x320)完全一致, 所以窗口/推屏/MADCTL/旋转/主题/背景图这条主链【一行都不用分叉】,
//   差别只在"上电初始化序列 / MADCTL 默认值 / 反显默认值"(见 display_ui.cpp 的 ili9341_hw_init)。
//   ★接线照旧: 把 ILI9341 模块的 SCK/MOSI/DC/RST/CS/BL 接到与 ST7789 完全相同的脚即可。
#define SCREEN_ST7567  1    // ST7567 SPI 单色 128x64
#define SCREEN_SSD1306 2    // SSD1306 I2C 单色 128x64
#define SCREEN_ST7789  3    // ST7789 SPI 彩色 TFT 320x240 (本机 U8g2 无此驱动, 用自定义设备接入)
// ★★2026-10-11: ST7789 有两种玻璃, 现在【两档都支持】——
//   ① 240x320(2.0/2.4 寸, 竖玻璃, 可横放成 320x240) = SCREEN_ST7789 (保留, 老用户语义不变);
//   ② 240x240(1.3 寸方屏)                            = SCREEN_ST7789_SQ (本次新增)。
//   两档【共用同一组引脚/同一个驱动核心】, 差别只在逻辑尺寸(320 宽 vs 240 方)与 MADCTL 默认值,
//   后台"屏幕类型"下拉现场切换、存 NVS(disp/type)。换模组不用改线、不用重烧。
#define SCREEN_ILI9341 4    // ILI9341 SPI 彩色 TFT 320x240 (2026-10-09 新增; 与 ST7789 共用引脚/驱动核心)
// ★出厂默认屏型 = ST7789(2026-10-07 起)。要换别的屏【不用重烧】: 后台"显示设置"里选一下,
//   存进 NVS 后一直有效(NVS 里的值优先于本默认值)。想彻底回到这个默认 = 整片重烧或清 NVS。
#define SCREEN_ST7789_SQ 5  // ST7789 SPI 彩色 TFT 240x240 (1.3寸方屏; 2026-10-11 新增)
#define SCREEN_DEFAULT SCREEN_ST7789
// ★三块 TFT 彩屏【共用同一组引脚(LCD2_*)与同一个驱动核心】的统一判定。
//   ★以后再加屏型(比如再添一种分辨率)只改这一处 —— 别在十几个地方重复写 `a==X || a==Y` 的组合,
//     历史教训: 加 ILI9341 时就有若干处漏改, 表现为"切过去黑屏/背光不亮/旋转没反应"。
#define IS_TFT_SCREEN(t) ((t) == SCREEN_ST7789 || (t) == SCREEN_ST7789_SQ || (t) == SCREEN_ILI9341)

// --- ★★2026-09-22 起: 三种屏【共用一组信号总线】, 后台切屏型即切协议 ---
// 复用依据: 三种屏的引脚全部是【运行期参数】, 不是芯片外设焊死的 ——
//   ST7567 / ST7789 走硬件 SPI(经 GPIO Matrix 路由到公共脚), SSD1306 走软件 I2C(U8g2 构造参数)。
//   换脚不降速: 硬件 SPI 由外设推、软件 I2C 由 CPU 推, 都与"接在哪根脚"无关。
// 复用原则(用户定的"只复用安全的, 有隐患的独立"):
//   共用 : CLK / DAT / DC / RST      —— 无隐患(同一时刻只有一种屏在工作)
//   独立 : CS ×2  —— 共用会被"误片选", 未选中的屏也跟着收命令 -> 自己乱显示
//          BL ×2  —— 两个模块的背光亮度极性可能相反, 共用一根只能二选一
// 结果: 屏幕占用从 12 个脚降到 8 个, 释放 GPIO15~18(GPIO13/14 留给 ST7567 的 CS/BL)。
//   公共组取原 ST7789 那一段(38~42 + 47) —— 正在用的彩色屏, 接线一根都不用动。
#define LCD_BUS_SCK   40   // 公共时钟: ST7567 SCK / SSD1306 SCL / ST7789 SCK
#define LCD_BUS_MOSI  41   // 公共数据: ST7567 MOSI(模块标 SDA) / SSD1306 SDA / ST7789 MOSI
#define LCD_BUS_DC    39   // 公共 DC  : ST7567 / ST7789 (SSD1306 无此线)
#define LCD_BUS_RST   38   // 公共复位: ST7567 / ST7789 (SSD1306 无此线)
// 公共总线的 SPI 时钟(2026-09-22: ST7567 由"软件翻脚"改为硬件 SPI 后新增)。
// ST7567 一帧 1024 字节: 软件 SPI ~25ms -> 硬件 8MHz 约 1.1ms(撕裂基本消失, 主循环占用同步下降)。
// ★2026-09-23: 8000000 -> 4000000。现场反馈 7567【残影】(旧画面淡影/错块残留在屏上)——
//   这正是"该总线在 8MHz 下边际"(排线长/无阻尼电阻/与 1306·7789 共板)的典型表现:
//   一个字节在 8MHz 下丢位或错位, 该 8×8 块就保持旧内容 ⇒ 看起来就是残影。
//   4MHz 一帧仍只要约 2.2ms(远低于 60ms 的画面节拍), 对撕裂/流畅度没有任何回退。
//   若降到 4MHz 仍有残影, 那不是总线速度问题, 方向转为【对比度(电子音量)】或 U8g2 的
//   ST7567 变体(JLX12864 / ERC12864 偏压不同) —— 两种变体偏压寄存器默认值不同。
#define LCD_BUS_SPI_HZ_ST7567  4000000UL    // ST7567 时钟(公共总线, 由 ST7567 字节层设定)
#define LCD_BUS_SPI_HZ_ST7789  20000000UL   // ST7789 时钟(写时序可到 ~62MHz; 排线长可降到 20000000)
// ★2026-10-05 从 40MHz 降到 20MHz: 320x240 每帧 153600 字节, 用杜邦/排线时 40MHz 极易花屏/雪花。
//   先求"画面正确"再求快; 排线短/焊接可靠时可改回 40000000UL 甚至 26000000UL。整帧跳过会大幅省帧。

// --- ST7567 (硬件 SPI 单色 128x64, 2026-09-22 由软件 SPI 提速而来) ---
// 模块排针: BLK+, GND, 3V3, SDA, SCK, DC, RESET, CS
// 注意: 标 "SDA" 的脚在 ST7567 上 = SPI 数据线(MOSI), 不是 I2C
#define LCD_SCK    LCD_BUS_SCK    // 时钟(共用; 硬件 SPI 经 GPIO Matrix 路由到本脚)
#define LCD_MOSI   LCD_BUS_MOSI   // 模块 SDA = SPI MOSI(共用)
#define LCD_DC     LCD_BUS_DC     // 数据/命令(共用)
#define LCD_RST    LCD_BUS_RST    // 复位(共用; U8g2 每次 begin() 会发一个复位脉冲)
#define LCD_CS     13             // ★独立片选(与 ST7789 的 42 分开, 杜绝误片选)
#define LCD_BL     14             // ★独立背光(与 ST7789 的 47 分开, 极性各自适配)
// --- SSD1306 (软件 I2C 单色 128x64, 自发光无背光) ---
// ★2026-09-23 修正: SSD1306 的 I2C 从"公共总线 40/41"改到【独立脚 GPIO15/16】。
//   原因: 40/41 上同时挂了 ST7567/ST7789 的【硬件 SPI】, SPI 与 I2C 不能在同一组线上并存 ——
//   两屏都焊在 40/41 时, ST7567 推 SPI 字节会被同线的 SSD1306 当成 I2C 帧收下, 表现为
//   1306 完全乱显示 + ST7567 收到错字节(残影)。移到 15/16 后三屏各自独立:
//     ST7567/ST7789 走 40/41(SPI) | SSD1306 走 15/16(I2C), 互不打架(1/2 脚现空闲)。
//   15/16 是"释放出来的空闲脚"(原 ST7567 的 CS/DC/RST/BL 已并入公共组), 正好空着。
//   ★物理接线: SSD1306 的 SCL/SDA 必须飞到 GPIO15/16(不再是 40/41)。
#define OLED_SCL   15   // 软件 I2C 时钟(独立脚, 与 40/41 SPI 总线全部分离; 1/2 脚现空闲)
#define OLED_SDA   16   // 软件 I2C 数据(独立脚)
// --- ST7789 (硬件 SPI 彩色 TFT 320x240 横屏) ---
// IO 选定依据: 避开 strapping(0/3/45/46)、内部 Flash(26~32)、OPI PSRAM 八线(33~37)、USB 串口(43/44)。
#define LCD2_SCK   LCD_BUS_SCK    // 共用
#define LCD2_MOSI  LCD_BUS_MOSI   // 共用(ST7789 只写不读, 无需 MISO)
#define LCD2_DC    LCD_BUS_DC     // 共用
#define LCD2_RST   LCD_BUS_RST    // 共用
#define LCD2_CS    42             // ★独立片选(低有效)
#define LCD2_BL    47             // ★独立背光(高有效点亮; 无操作超时自动熄灭)
// ★★方向与 MADCTL(0x36) —— ST7789 显示正确与否的命门
//   硬件事实: ST7789 芯片的 RAM 是【240 列 × 320 行】(原生竖屏玻璃)。所以:
//     · 当【竖屏 240x320】用: 行列不用交换 -> MADCTL 的 MV(bit5) 必须 = 0;
//     · 当【横屏 320x240】用: 必须打开 MV 让芯片交换行列, 否则列地址窗口只能到 239,
//       而我们要发 CASET 0..319 -> 越界回绕 -> 【花屏/斜纹/右侧混入左侧内容】。
//   MADCTL 位定义: bit7=MY 行序, bit6=MX 列序, bit5=MV 行列交换, bit4=ML 刷新序, bit3=BGR 顺序。
//   ★同一个模组, 装成横的/竖的, 看到的排版相差 90° —— 与其猜外壳怎么装, 不如现场切:
//   ★后台"显示设置"里的【旋转】对 ST7789 同样有效(2026-10-06 打通): 它被翻译成
//       0° / 180° -> 横屏 320x240      90° / 270° -> 竖屏 240x320
//       其中 180°/270° 再把 MADCTL 的 MX|MY 取反(^0xC0) 做硬件上下颠倒, 零代价。
//     (不能把旋转交给 U8g2 的软件旋转: 那会让宽高对调而 tile 数不匹配 -> 分页错乱)
//   现场调试命令:
//       串口 O = 切【横屏 320x240 / 竖屏 240x320】(等价于选 90°/0°; 存 NVS)
//       串口 K = 在当前方向内轮换 MADCTL(治"上下颠倒/镜像")
//       串口 J = 翻转反显(治"整片发白像底片")
//   以上三项都【写 NVS】, 重启后仍然生效, 不需要回头改这个文件。
#define ST7789_ORIENT_DEFAULT 0   // ★默认方向: 0=横屏 320x240(照参考图的排版) / 1=竖屏 240x320
// 各方向下的 MADCTL 初值(首次上电用; 之后以 NVS 里现场试出来的值为准)
#define ST7789_MADCTL_LAND   0x60 // 横屏(320x240): MX+MV(列序反转 + 行列交换) —— 最常用
#define ST7789_MADCTL_PORT   0x00 // 竖屏(240x320): 全部为 0(玻璃原生方向)
//   备选(横屏): 0xA0 = MY+MV(画面上下颠倒时用); 0xE0 / 0x20 = 上面两个的镜像(少数模组)。
//   若【颜色红蓝颠倒】, 把值再叠 bit3(0x08): 如 0x68 / 0xA8。
#define ST7789_MADCTL   ST7789_MADCTL_LAND   // 兼容别名(旧代码/旧注释引用)
// ---- 240x240 方屏(1.3 寸)的 MADCTL 初值(2026-10-11 新增) ----
// ★方屏没有"横竖之分"(240x240 两个方向尺寸相同), 所以 MV 位不再承担"换方向"的职责 ——
//   它这时只是把画面整体转 90°(行列对调), 用于满足"模组排线在上/在下"的差异。
//   各厂家 1.3 寸 ST7789 模组常见三种默认值:
//     0x00 = 全 0                     (原生方向, 最常见)
//     0x60 = MX + MV                  (画面旋转 90°, 排线在左侧的模组常用)
//     0xC0 = MX + MY                  (画面上下颠倒 180°)
//   ★拿不准就用串口 K 现场轮换(候选表已按"方屏"单独分组, 见 display_ui.cpp), 试对了自动存 NVS。
//   若【颜色红蓝颠倒】, 再叠 bit3(0x08)。
#define ST7789_MADCTL_SQ     0x00 // 240x240 方屏: 原生方向
// ★反显(0x21 INVON / 0x20 INVOFF): ST7789 模组有的出厂需要反显、有的不需要。
//   若画面【整体发白、像照片底片】, 把这里改成 0; 若偏暗/颜色发闷, 保持 1。
#define ST7789_INVON   1
// ★调色板主题(2026-10-06 起可选; 本屏是 1bpp —— 一帧【物理上只有两个颜色】, “彩色”不是开关):
//     0 = 经典黑白   : 白字(0xFFFF) + 黑底(0x0000)    ← 默认(与主线 240x240 一致, 最通用)
//     1 = 深蓝图片风 : 亮白青 RGB(232,248,255)=RGB565 0xEFDF + 深蓝底 RGB(14,58,107)=RGB565 0x09CD
//     2 = 墨绿夜光   : 亮绿 RGB(124,255,158)=RGB565 0x7FF3 + 近黑底 RGB(6,20,12)=RGB565 0x00A1
//   ★值必须是 16-bit RGB565(不是 24-bit RGB888!): 写 0xE8F8FF 会被静默截断成 0xF8FF(品红)。
//   运行时可用串口 Q 现场轮换(立即生效), 满意后把值回填到这里固化。
#define ST7789_THEME   0

// ---- ILI9341 面板默认参数(2026-10-09 新增; 与 ST7789 共用引脚, 只是"芯片不同") ----
// ★为什么 ILI9341 的 MADCTL 值不一样: ILI9341 绝大多数模组的 BGR 位(bit3=0x08)【必须置 1】,
//   否则【红蓝互换】(肤色变蓝、红色变青)。ST7789 则相反, 默认不需要 BGR。
//   ILI9341 位定义与 ST7789 一致: bit7=MY 行序, bit6=MX 列序, bit5=MV 行列交换, bit4=ML, bit3=BGR。
